//! Explicit retained generated-root rollback; never registers or connects.
#![allow(dead_code)]
#[cfg(all(windows, feature = "native-test-hooks"))]
#[path = "../../twodrive-dev/src/local_files.rs"]
mod local_files;
#[cfg(all(windows, feature = "native-test-hooks"))]
#[path = "../../twodrive-dev/src/model.rs"]
mod model;
#[cfg(all(windows, feature = "native-test-hooks"))]
#[path = "../../twodrive-dev/src/provider.rs"]
mod provider;
#[cfg(all(windows, feature = "native-test-hooks"))]
#[path = "../../twodrive-dev/src/provider_guard.rs"]
mod provider_guard;
#[cfg(all(windows, feature = "native-test-hooks"))]
extern crate twodrive_cfapi_probe as twodrive_local_files;
#[cfg(all(windows, feature = "native-test-hooks"))]
#[path = "../../twodrive-dev/src/native_local_fixture.rs"]
mod native_local_fixture;
#[cfg(all(windows, feature = "native-test-hooks"))]
fn main() -> anyhow::Result<()> {
    let mut args = std::env::args_os().skip(1);
    let root = std::path::PathBuf::from(
        args.next()
            .ok_or_else(|| anyhow::anyhow!("root required"))?,
    );
    let backup = std::path::PathBuf::from(
        args.next()
            .ok_or_else(|| anyhow::anyhow!("NEW backup required"))?,
    );
    anyhow::ensure!(args.next().is_none(), "unexpected arguments");
    let root = std::path::absolute(root)?;
    let backup = std::path::absolute(backup)?;
    let state = root.with_extension("engine-state");
    anyhow::ensure!(
        state.join("fixture.sqlite3").is_file() && state.join("cache").is_dir(),
        "existing generated journal required"
    );
    let mut bridge = None;
    twodrive_local_files::native::recover_retained_generated(&root, &backup, |dataset, id| {
        // Do not open or mutate journal state until native and current-user
        // Shell identities and all retained files have been verified.
        if bridge.is_none() {
            bridge = Some(
                local_files::LocalFileBridge::generated_fixture_dataset(
                    twodrive_core::Database::new(state.join("fixture.sqlite3")),
                    &state.join("cache"),
                    dataset,
                    std::sync::Arc::default(),
                )
                .map_err(|e| e.to_string())?,
            );
        }
        bridge
            .as_ref()
            .ok_or("journal unavailable")?
            .journal()
            .record_native_edit(id)
            .map_err(|e| e.to_string())
    })
    .map_err(anyhow::Error::msg)?;
    println!(
        "retained generated bytes preserved; native edits vetoed in journal; Shell and CFAPI unregistered"
    );
    Ok(())
}
#[cfg(not(all(windows, feature = "native-test-hooks")))]
fn main() {
    eprintln!("requires Windows and native-test-hooks");
}
