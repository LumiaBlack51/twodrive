final desktopLocale = ValueNotifier<String>('zh');
String uiText(String chinese, String english) =>
    desktopLocale.value == 'en' ? english : chinese;

final _placeholder = RegExp(r'\{arg(\d+)\}');
String tr(String key, [List<Object?> values = const []]) {
  final message = desktopLocale.value == 'en' ? (_english[key] ?? key) : key;
  if (values.isEmpty) return message;
  return message.replaceAllMapped(
    _placeholder,
    (m) => values[int.parse(m[1]!)].toString(),
  );
}

